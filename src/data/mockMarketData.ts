/**
 * Generates realistic candlestick chart series based on stock current price and timeframe.
 */
export function generateCandles(stock: Stock, timeframe: Timeframe): Candle[] {
  const count = timeframe === '1D' ? 36 : timeframe === '5D' ? 45 : timeframe === '1M' ? 30 : timeframe === '1Y' ? 52 : 40;
  const candles: Candle[] = [];
  
  // Base volatility and trend from stock attributes
  const isBullish = stock.changePercent >= 0;
  const volatility = Math.max(0.008, Math.min(0.035, (stock.beta || 1.0) * 0.015));
  let current = stock.price * (isBullish ? 0.95 : 1.05);

  const now = Date.now();
  const stepMs = timeframe === '1D' ? 10 * 60 * 1000 : timeframe === '5D' ? 60 * 60 * 1000 : 24 * 60 * 60 * 1000;
  const startTs = now - count * stepMs;

  for (let i = 0; i < count; i++) {
    const timestamp = startTs + i * stepMs;
    const dateObj = new Date(timestamp);
    const timeLabel = timeframe === '1D'
      ? dateObj.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit', hour12: false })
      : `${dateObj.getMonth() + 1}/${dateObj.getDate()}`;

    // Target final close near stock.price
    const progress = i / count;
    const targetDrift = (stock.price - current) * (progress * 0.4);
    const noise = (Math.random() - 0.48) * current * volatility;
    
    const open = current;
    const close = i === count - 1 ? stock.price : Math.max(1, open + targetDrift + noise);
    const high = Math.max(open, close) + Math.random() * (current * volatility * 0.8);
    const low = Math.min(open, close) - Math.random() * (current * volatility * 0.8);
    const volume = Math.round((stock.volume / count) * (0.6 + Math.random() * 0.8));

    candles.push({
      time: timeLabel,
      timestamp,
      open: Number(open.toFixed(2)),
      high: Number(high.toFixed(2)),
      low: Number(low.toFixed(2)),
      close: Number(close.toFixed(2)),
      volume,
    });

    current = close;
  }

  return candles;
}
